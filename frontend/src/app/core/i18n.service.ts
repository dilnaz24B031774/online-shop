const DICTS: Record<Lang, Dict> = { en: EN, ru: RU, kk: KK };
const KEY = 'sauda.lang';

/**
 * Multilanguage support: the whole interface switches without reloading.
 * Product and category names come from the database (name_en / name_ru / name_kk).
 */
@Injectable({ providedIn: 'root' })
export class I18nService {
  private doc = inject(DOCUMENT);
  readonly lang = signal<Lang>(this.stored());

  constructor() {
    this.doc.documentElement.lang = this.lang();
  }

  use(lang: Lang) {
    this.lang.set(lang);
    this.doc.documentElement.lang = lang;
    try { localStorage.setItem(KEY, lang); } catch { /* ignore */ }
  }

  /** Interface text:  t('cart.title')  or  t('product.left', {n: 6}) */
  t(key: string, params?: Record<string, string | number>): string {
    let text = DICTS[this.lang()][key] ?? EN[key] ?? key;
    if (params) Object.entries(params).forEach(([k, v]) => (text = text.replace(`{${k}}`, String(v))));
    return text;
  }

  /** Database text in the current language, English if the translation is empty. */
  pick(obj: any, field: 'name' | 'description' = 'name'): string {
    if (!obj) return '';
    return obj[`${field}_${this.lang()}`] || obj[`${field}_en`] || '';
  }

  private stored(): Lang {
    try {
      const v = localStorage.getItem(KEY) as Lang | null;
      if (v && v in DICTS) return v;
    } catch { /* ignore */ }
    return 'en';
  }
}
